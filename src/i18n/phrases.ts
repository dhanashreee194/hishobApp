export function translate(locale: Locale, value: string): string {
  if (locale !== 'en' || !value) {
    return value;
  }
  if (en[value]) {
    return en[value];
  }
  if (value.includes(' · ')) {
    return value
      .split(' · ')
      .map(part => translate(locale, part))
      .join(' · ');
  }
  if (value.includes(', ')) {
    return value
      .split(', ')
      .map(part => translate(locale, part))
      .join(', ');
  }
  if (value.startsWith('नोंदवले:')) {
    return `Recorded by:${value.slice('नोंदवले:'.length)}`;
  }
  const running = ' पर्यंत एकत्रित';
  if (value.endsWith(running)) {
    return `${value.slice(0, -running.length)} running total`;
  }
  const month = value.split(' ')[0];
  if (en[month] && value.slice(month.length).match(/^ \d{4}$/)) {
    return `${en[month]}${value.slice(month.length)}`;
  }
  const quantityLabel = value.match(/^प्रमाण \((.+)\)$/);
  if (quantityLabel) {
    return `Quantity (${translate(locale, quantityLabel[1])})`;
  }
  if (value.endsWith(' नोंदी')) {
    return `${value.slice(0, -' नोंदी'.length)} entries`;
  }
  if (value.endsWith(' ग्राहक')) {
    return `${value.slice(0, -' ग्राहक'.length)} customers`;
  }
  const lastSpace = value.lastIndexOf(' ');
  if (lastSpace > 0) {
    const tail = value.slice(lastSpace + 1);
    if (tail === 'किलो' || tail === 'जुडी' || tail === 'लिटर' || tail === 'नग') {
      return `${value.slice(0, lastSpace)} ${en[tail]}`;
    }
  }
  return value;
}
